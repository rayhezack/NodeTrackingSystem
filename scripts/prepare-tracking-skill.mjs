import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const source = new URL('skills/pollo-tracking-design/', root);
const files = ['SKILL.md', 'references/reuse-contract.md', 'references/planning.md', 'references/design.md'];
const documents = Object.fromEntries(files.map((file) => [file, readFileSync(new URL(file, source), 'utf8').replace(/\r\n/g, '\n')]));
const entry = documents['SKILL.md'];
if (!/^---\nname: pollo-tracking-design\ndescription: .+\n---\n/.test(entry)) throw new Error('Invalid tracking Skill frontmatter');
for (const file of files.slice(1)) {
  if (!entry.includes(`](${file})`)) throw new Error(`Skill does not reference ${file}`);
  if (!documents[file].trim()) throw new Error(`Empty Skill reference: ${file}`);
}
const hash = createHash('sha256').update(JSON.stringify(documents)).digest('hex');
const output = `// Generated by scripts/prepare-tracking-skill.mjs. Edit skills/pollo-tracking-design instead.\nexport const TRACKING_SKILL_SOURCE_HASH = ${JSON.stringify(hash)};\nexport const TRACKING_SKILL_DOCUMENTS = ${JSON.stringify(documents, null, 2)} as const;\n`;
const target = new URL('shared/tracking-skill.generated.ts', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Tracking Skill bundle is stale. Run npm run skill:tracking:prepare');
  console.log(`Tracking Skill bundle matches source (${hash.slice(0, 12)})`);
} else {
  writeFileSync(target, output);
  console.log(`Prepared ${files.length} Skill files: ${fileURLToPath(target)}`);
}
